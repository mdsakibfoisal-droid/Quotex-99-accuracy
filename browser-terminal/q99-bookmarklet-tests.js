const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");

const source = fs.readFileSync("q99-bookmarklet.js", "utf8").trim();
assert.ok(source.startsWith("javascript:"), "bookmarklet must start with javascript:");
const script = source.slice("javascript:".length);
assert.ok(script.length > 1000, "bookmarklet source must not be empty");
assert.doesNotThrow(() => new vm.Script(script), "bookmarklet must parse as JavaScript");
assert.match(script, /q99-floating-panel/, "bookmarklet should create its panel");
assert.match(script, /q99-chart/, "chart screenshot input should exist");
assert.match(script, /q99-ref/, "reference image input should exist");
assert.match(script, /q99-threshold/, "similarity threshold input should exist");
assert.match(script, /function extract/, "image feature extraction should exist");
assert.match(script, /body:/, "candle body feature should be measured");
assert.match(script, /upper:/, "upper wick feature should be measured");
assert.match(script, /lower:/, "lower wick feature should be measured");
assert.match(script, /function score/, "sequence similarity scoring should exist");
assert.match(script, /WAIT/, "safe WAIT state must exist");
assert.match(script, /জেতার সম্ভাবনা নয়/, "similarity score must not be presented as win probability");
assert.doesNotMatch(script, /fetch\s*\(|XMLHttpRequest|\.submit\s*\(/, "prototype must not fetch external data or submit forms");
assert.doesNotMatch(script, /placeTrade|buyNow|sellNow/i, "prototype must not implement trading actions");
console.log("Q99 screenshot-comparison syntax/safety checks passed");
